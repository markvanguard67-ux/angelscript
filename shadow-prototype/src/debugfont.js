export function drawText(fb, text, x, y, color = [255, 255, 255], alpha = 255, scale = 1) {
  const str = String(text).toUpperCase();
  let cx = x;
  for (const ch of str) {
    const g = GLYPHS[ch] || GLYPHS['?'];
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) {
        if (g[r][c] !== '1') continue;
        if (scale === 1) fb.setPixel(cx + c, y + r, color[0], color[1], color[2], alpha);
        else fb.rect(cx + c * scale, y + r * scale, scale, scale, color[0], color[1], color[2], alpha);
      }
    }
    cx += 4 * scale;
  }
  return cx - x;
}

export function textWidth(text, scale = 1) { return String(text).length * 4 * scale - scale; }

